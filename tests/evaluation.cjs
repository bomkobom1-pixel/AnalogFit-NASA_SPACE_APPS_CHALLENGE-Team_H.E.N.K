/* Enlarged map and evaluation response acceptance checks on file://. */
const {chromium}=require('../.test-tools/node_modules/playwright');
const {pathToFileURL}=require('url'),path=require('path'),fs=require('fs');
const root=path.resolve(__dirname,'..'),out=path.join(root,'test-artifacts');
const check=(v,m)=>{if(!v)throw Error(m);};
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-unsafe-swiftshader','--use-angle=swiftshader']});
 try{
  const context=await browser.newContext({offline:true,viewport:{width:1440,height:900}}),page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(root,'index.html')).href);
  await page.waitForFunction(()=>document.body.dataset.boot==='ready');await page.locator('#bootScreen').waitFor({state:'hidden'});
  check(await page.evaluate(()=>analogfit.state.lang==='en'),'English default missing');
  const before=await page.locator('#stage').boundingBox();
  await page.locator('#btnMapFocus').click();
  const expanded=await page.locator('#stage').boundingBox();
  check(expanded.width>=1439&&expanded.height>=899&&expanded.width>before.width,'Map did not fill viewport');
  check(await page.evaluate(()=>document.getElementById('controls').inert),'Hidden sidebar still focusable');
  await page.locator('#openSiteRankings').click();
  check(await page.locator('#controls').isVisible(),'Fullscreen browse action failed');
  await page.locator('#rankSites button').first().click();
  await page.locator('#locationDashboard h1').waitFor({state:'visible'});
  check(await page.locator('#controls').isHidden(),'Expanded sidebar did not close after selection');
  check((await page.locator('#stage').boundingBox()).width>=1439,'Expanded map shrank behind dossier');
  await page.locator('#closeInspector').click();
  await page.locator('#mapTargetSel').selectOption('T3');
  check(await page.evaluate(()=>analogfit.state.target==='T3'),'Expanded target selector failed');
  await page.screenshot({path:path.join(out,'evaluation-expanded-map.png'),animations:'disabled'});
  await page.locator('#btnMapFocus').click();
  check(await page.evaluate(()=>!AnalogFitExplorer.expanded&&!document.getElementById('controls').inert),'Expanded exit did not restore workspace');
  await page.locator('#btnMapFullscreen').click();
  await page.waitForFunction(()=>document.fullscreenElement===document.getElementById('workspace')||!document.getElementById('mapViewNotice').hidden);
  const native=await page.evaluate(()=>!!document.fullscreenElement);
  check(await page.evaluate(()=>AnalogFitExplorer.expanded),'Fullscreen did not provide expanded fallback');
  await page.evaluate(()=>AnalogFitScience.open());
  check(await page.locator('#dlgScience').isVisible(),'Scientific dialog unavailable above fullscreen map');
  await page.locator('#scienceBody .close').click();
  await page.locator('#btnMapFocus').click();
  await page.waitForFunction(()=>!document.fullscreenElement&&!AnalogFitExplorer.expanded);
  await page.evaluate(()=>Object.defineProperty(document,'fullscreenEnabled',{configurable:true,get:()=>false}));
  await page.locator('#btnMapFullscreen').click();
  check(await page.locator('#mapViewNotice').isVisible(),'Unsupported fullscreen fallback unexplained');
  await page.keyboard.press('Escape');check(await page.evaluate(()=>!AnalogFitExplorer.expanded),'Fallback Escape failed');
  await page.locator('#btnWalkthrough').click();
  check(await page.locator('.tour-case').count()===2,'Evidence cases missing');
  await page.screenshot({path:path.join(out,'evaluation-tour.png'),animations:'disabled'});
  await page.locator('[data-inspect-case=HYP_H2]').click();
  const h2=await page.evaluate(()=>{const p=analogfit.places.find(p=>p.id==='HYP_H2');return {dataset:p.raw.terrainDataset,spacing:p.raw.demSpacing,points:p.raw.dem.length,coverage:analogfit.score(p).covReal,features:ANALOGFIT.targets.T1.supportedFeatures};});
  check(h2.dataset==='copernicus_glo30'&&h2.spacing===500&&h2.points===9,'Polar terrain mesh/source is incorrect');
  check(Math.abs(h2.coverage-.6)<1e-12,'Recovered slope did not add correct supported coverage');
  check(!h2.features.includes('T')&&!h2.features.includes('I'),'Diviner context incorrectly added evidence');
  check((await page.locator('.target-thermal-context').innerText()).includes('85.4 K / 227.0 K'),'Real Diviner context absent');
  check((await page.locator('#terrainCap').innerText()).includes('500 m'),'Coarse mesh spacing hidden');
  await page.locator('#btnScience').click();
  check((await page.locator('#scienceBody').innerText()).includes('naive_raw_minmax'),'Baseline diagnostics missing');
  check(await page.locator('a[href="analogfit_full_ablation.csv"]').count()===1,'Full ablation export missing');
  await page.keyboard.press('Escape');
  await page.evaluate(()=>analogfit.select('BG578'));
  check(await page.locator('#terrain').count()===1,'Verified global terrain not available');
  await page.locator('#btnScience').click();
  const downloaded=page.waitForEvent('download');await page.locator('#exportEvidence').click();
  const file=path.join(out,'evaluation-multitile-evidence.json');await (await downloaded).saveAs(file);
  const evidence=JSON.parse(fs.readFileSync(file,'utf8'));
  check(evidence.earthTerrainSources.length===2&&evidence.earthTerrainPatch.z.length===9,'Evidence export omitted a source tile');
  check(evidence.earthTerrainSources.every(s=>s.sha256.length===64),'Multi-tile checksums missing');
  await page.locator('#scienceBody .close').click();
  await page.locator('#closeInspector').click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('#btnMapFocus').click();
  const mobile=await page.locator('#stage').boundingBox();check(mobile.width<=391&&mobile.height>=843,'Mobile expanded map dimensions incorrect');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile overflow');
  await page.locator('[data-view="3d"]').click();await page.waitForFunction(()=>!!document.querySelector('#globe canvas'));
  await page.waitForTimeout(500);await page.screenshot({path:path.join(out,'evaluation-mobile-globe.png'),animations:'disabled'});
  await page.locator('#btnMapFocus').click();
  await page.locator('[data-lang=id]').click();await page.reload();
  await page.waitForFunction(()=>document.body.dataset.boot==='ready');await page.locator('#bootScreen').waitFor({state:'hidden'});
  check(await page.evaluate(()=>analogfit.state.lang==='id'),'Existing Indonesian preference lost');
  check(errors.length===0,'Browser errors: '+errors.join('\n'));
  const report={defaultMap:before,expandedMap:expanded,nativeFullscreen:native,fallbackAndEscape:true,selectionAndContextControls:true,
   defaultEnglishPreservesSavedIndonesian:true,evidenceCases:2,h2,divinerContextWithoutScoreInflation:true,globalTerrain:true,baselineAndAblationVisible:true,mobileExpanded:mobile,pageErrors:errors};
  fs.writeFileSync(path.join(out,'evaluation-ui-report.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
